import { HttpClient, provideHttpClient } from '@angular/common/http';
import {
  type ApplicationConfig,
  provideBrowserGlobalErrorListeners,
  provideZonelessChangeDetection,
  SecurityContext,
} from '@angular/core';
import { provideRouter, withInMemoryScrolling } from '@angular/router';
import { DOCS_MAPPER_OPTIONS, DOCS_ROOT } from '@app/app.constant';
import { routes } from '@app/app.routes';
import { markedOptionsFactory } from '@app/marked-options-factory';
import { MARKED_OPTIONS, provideMarkdown, withClipboard, withEmoji, withPrism } from '@fsegurai/ngx-markdown';
import { AnchorService } from '@shared/anchor';
import { ClipboardButtonComponent } from '@shared/clipboard-button';
import { provideSidenav, withManifest, withSearchIndex } from 'ngx-sidenav';

/**
 * The search worker (`sidenav.worker.ts`), used by the library for large search indexes only. Without `Worker`
 * (tests, server) or when the worker fails, the library searches on the main thread.
 */
export function createSidenavWorker(): Worker {
  return new Worker(new URL('./sidenav.worker', import.meta.url), { type: 'module' });
}

export const appConfig: ApplicationConfig = {
  providers: [
    provideBrowserGlobalErrorListeners(),
    provideZonelessChangeDetection(),
    provideHttpClient(),
    provideRouter(
      routes,
      withInMemoryScrolling({
        anchorScrolling: 'enabled',
        scrollPositionRestoration: 'enabled',
      }),
    ),
    provideMarkdown({
      loader: HttpClient,
      // Prism highlights the code blocks (the Prism global loaded in angular.json), Emoji renders the `[emoji]`
      // shortnames, and Clipboard gives the code blocks the demo copy button
      plugins: [withPrism(), withEmoji(), withClipboard({ buttonComponent: ClipboardButtonComponent })],
      markedOptions: {
        provide: MARKED_OPTIONS,
        useFactory: markedOptionsFactory,
        deps: [AnchorService],
      },
      // Angular's HTML sanitizer strips `id` attributes, which the heading anchors (and the search results linking to
      // them) need. Only trusted content is rendered: the demo's own versioned docs (same origin) and templates. Never pass
      // user-provided Markdown through this configuration.
      sanitize: SecurityContext.NONE,
    }),
    // The demo dogfoods the library: its own docs, generated by @fsegurai/manifest-generator, build the menu and the
    // search index (`bun run generate:manifest`).
    provideSidenav(
      {},
      withManifest({ source: `${DOCS_ROOT}/manifest.json`, mapperOptions: DOCS_MAPPER_OPTIONS }),
      withSearchIndex({
        source: `${DOCS_ROOT}/search-index.json`,
        mapperOptions: DOCS_MAPPER_OPTIONS,
        worker: createSidenavWorker,
      }),
    ),
  ],
};
